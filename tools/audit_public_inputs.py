"""Check distributed public inputs for unexpected fuel identities and research artifacts."""

import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]


def audit(root=ROOT):
    """Audit IDs, input material names and distributed files under ``root``; return counts.

    This checks the defined public dataset and obvious publication mistakes.
    It is not a general secret scanner and does not inspect Git history.
    """
    root = Path(root)
    allowed_pins = {str(i) for i in range(900001, 900112)}
    generic_indices = {str(i) for i in range(1, 16)}
    problems, checked = [], 0
    for path in root.rglob("*"):
        if not path.is_file() or ".git" in path.relative_to(root).parts:
            continue
        relative = path.relative_to(root)
        if relative.parts[0] in {"results", "nuclear_data"} and path.name != ".gitkeep":
            problems.append(f"Local output/nuclear data must stay outside a release: {relative}")
        if len(relative.parts) > 1 and relative.parts[0] == "reevaluation_iv_4_5_2":
            if relative.parts[1].startswith(("production", "smoke")) or (
                relative.parts[1] == "validation" and path.name != ".gitkeep"
            ):
                problems.append(f"Reevaluation run artifact: {relative}")
        if "__pycache__" in relative.parts:
            problems.append(f"Generated bytecode directory: {relative}")
        if path.suffix in (".h5", ".zip", ".sqlite3", ".pyc"):
            problems.append(f"Runtime/archive artifact: {relative}")
        try:
            source = path.read_text()
        except UnicodeDecodeError:
            continue
        unexpected = set(re.findall(r"\bfuel_(\d+)\b", source)) - allowed_pins - generic_indices
        if unexpected:
            problems.append(f"Unexpected fuel identity in {relative}")
        checked += 1
    inventory = json.loads((root / "config/fuel_inventory.json").read_text())
    if set(inventory["fuels"]) != {str(i) for i in range(900001, 900109)}:
        problems.append("Mutable inventory IDs differ from the 108 public pins.")
    material_xml = ET.parse(root / "config/materials.xml").getroot()
    actual = {
        m.get("name")
        for m in material_xml.findall("material")
        if m.get("name", "").startswith("fuel_")
    }
    expected = {f"fuel_{pin}_{axial:02d}" for pin in allowed_pins for axial in range(1, 16)}
    if actual != expected:
        problems.append("Fuel material names differ from the 1665 public segments.")
    if problems:
        raise ValueError("\n".join(problems))
    return dict(
        passed=True,
        checked_text_files=checked,
        public_pins=111,
        regular_inventory_entries=108,
        fuel_materials=len(actual),
        git_history_checked=False,
        scope="Public working tree only",
    )


if __name__ == "__main__":
    print(json.dumps(audit(), indent=2))
